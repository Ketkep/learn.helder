/** The land, as one path. */
export const land = [eurasia, africa, ...islands].map(polygon).join('');

/** The sea route, as a smooth path, and the places on it. */
const pts: [number, number][] = route.map((r) => [px(r.lon), py(r.lat)]);
export const routePath = smooth(pts);

/** How far along the route each named place is (0 to 1), counted along straight lines. */
export const landmarks = (() => {
  const lengths = pts.map((p, i) => (i === 0 ? 0 : Math.hypot(p[0] - pts[i - 1][0], p[1] - pts[i - 1][1])));
  const total = lengths.reduce((a, b) => a + b, 0);
  let run = 0;
  const out: { at: number; where: string }[] = [];
  route.forEach((r, i) => {
    run += lengths[i];
    if (r.where) out.push({ at: run / total, where: r.where });
  });
  return out;
})();

